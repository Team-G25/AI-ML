import numpy as np
import faiss
import torch
from sklearn.preprocessing import normalize
from transformers import AutoTokenizer, AutoModel, AutoModelForCausalLM
from konlpy.tag import Okt
from sentence_transformers import SentenceTransformer
import re

class MailGenerator:
    def __init__(self,
                 embed_model,
                 gen_model,
                 embed_file,
                 text_file,
                 index_file,
                 keyword_boost=0.05,
                 max_length=2048,
                 max_new_tokens=150,
                 max_email_token_length=500,
                 sim_threshold=0.93):

        self.embed_tokenizer = AutoTokenizer.from_pretrained(embed_model)
        self.embed_model = AutoModel.from_pretrained(embed_model)
        self.gen_tokenizer = AutoTokenizer.from_pretrained(gen_model)
        self.gen_model = AutoModelForCausalLM.from_pretrained(gen_model)
        self.st_model = SentenceTransformer(embed_model)
        self.okt = Okt()

        self.EMBED_FILE = embed_file
        self.TEXT_FILE = text_file
        self.INDEX_FILE = index_file
        self.keyword_boost = keyword_boost
        self.max_length = max_length
        self.max_new_tokens = max_new_tokens
        self.max_email_token_length = max_email_token_length
        self.sim_threshold = sim_threshold

    def get_embedding(self, text):
        inputs = self.embed_tokenizer(text, return_tensors='pt', padding=True, truncation=True, max_length=512)
        with torch.no_grad():
            output = self.embed_model(**inputs).last_hidden_state.mean(dim=1)
        return output.squeeze().numpy().astype("float32")

    def extract_keywords(self, text):
        return [word for word, pos in self.okt.pos(text) if pos in ["Noun", "Verb", "Adjective"]]

    def search_similar_emails(self, user_request, top_k=5):
        embeddings = np.load(self.EMBED_FILE)
        email_texts = np.load(self.TEXT_FILE, allow_pickle=True)
        index = faiss.read_index(self.INDEX_FILE)

        user_emb = self.get_embedding(user_request).reshape(1, -1)
        user_emb = normalize(user_emb, axis=1)
        keywords = self.extract_keywords(user_request)

        D, I = index.search(user_emb.astype("float32"), len(email_texts))

        results = []
        for i, idx in enumerate(I[0]):
            email = email_texts[idx]
            sim_score = float(D[0][i])
            keyword_count = sum(kw in email for kw in keywords)
            final_score = sim_score + self.keyword_boost * keyword_count
            results.append((email, final_score))
        results.sort(key=lambda x: x[1], reverse=True)
        return results[:top_k]

    def generate_email_from_context(self, user_request, context_emails):
        context_list = []
        total_token_count = 0
        prompt_suffix = f"\n\n[요청] {user_request}\n[완성된 이메일]\n"
        suffix_tokens = self.gen_tokenizer.encode(prompt_suffix, add_special_tokens=False)
        available_budget = self.max_length - self.max_new_tokens - len(suffix_tokens)

        for email_text, _ in context_emails:
            email_tokens = self.gen_tokenizer.encode(email_text, add_special_tokens=False)
            sep_tokens = self.gen_tokenizer.encode("\n---\n", add_special_tokens=False)
            sep_len = len(sep_tokens)
            if len(email_tokens) > self.max_email_token_length:
                continue
            extra_tokens = sep_len if context_list else 0
            if total_token_count + len(email_tokens) + extra_tokens <= available_budget:
                context_list.append(email_text)
                total_token_count += len(email_tokens) + extra_tokens

        context = "\n---\n".join(context_list)
        prompt = f"{context}{prompt_suffix}"

        input_ids = self.gen_tokenizer.encode(prompt, return_tensors="pt")
        attention_mask = torch.ones_like(input_ids)

        output = self.gen_model.generate(
            input_ids=input_ids,
            attention_mask=attention_mask,
            max_new_tokens=self.max_new_tokens,
            min_new_tokens=50,
            early_stopping=True,
            do_sample=True,
            temperature=0.6,
            top_k=25,
            top_p=0.95,
            pad_token_id=self.gen_tokenizer.eos_token_id
        )

        decoded = self.gen_tokenizer.decode(output[0], skip_special_tokens=True)
        return decoded.split("[완성된 이메일]")[-1].strip()

    def is_complete_sentence(self, sentence):
        sentence = sentence.strip()
        if not sentence:
            return False
        if sentence[-1] in ".?!":
            return True
        if re.search(r"(올림|드림)$", sentence):
            return True
        m = re.match(r"^(\d+\.\s*|[•\-–]\s*)", sentence)
        if m:
            if len(sentence) <= 7 or re.search(r"([가-힣])$", sentence):
                return False
            if re.search(r"(다|요|니다|습니다|줍니다|바랍니다|[.?!:])$", sentence):
                return True
            return False
        return False

    def remove_similar_sentences(self, email):
        email = "\n".join([l for l in email.split('\n')
                           if not l.strip().startswith(("[요청]", "[답변]", "[완성된 이메일]"))])
        paragraphs = re.split(r"\n\s*\n", email)
        clean_paragraphs = []
        seen_paragraphs = set()

        for para in paragraphs:
            lines = [l for l in para.split('\n') if l.strip()]
            if not lines:
                continue
            seen = set()
            unique_lines = []
            for l in lines:
                l_clean = l.strip().rstrip('.').rstrip()
                if l_clean and l_clean not in seen:
                    unique_lines.append(l)
                    seen.add(l_clean)
            if len(unique_lines) == 1:
                filtered_lines = unique_lines
            else:
                embeddings = self.st_model.encode(unique_lines)
                keep = [0]
                for i in range(1, len(unique_lines)):
                    sims = [np.dot(embeddings[i], embeddings[j]) /
                            (np.linalg.norm(embeddings[i]) * np.linalg.norm(embeddings[j])) for j in keep]
                    if max(sims) < self.sim_threshold:
                        keep.append(i)
                filtered_lines = [unique_lines[i] for i in keep]
            if filtered_lines:
                para_text = '\n'.join(filtered_lines)
                if norm_para not in seen_paragraphs:
                    clean_paragraphs.append(para_text)
                    seen_paragraphs.add(norm_para)

        full_mail = '\n\n'.join(clean_paragraphs)
        lines = full_mail.split('\n')
        if lines and not self.is_complete_sentence(lines[-1]):
            lines.pop()
        return '\n'.join(lines).lstrip('- \n')

    def make_email(self, user_request):
        context_emails = self.search_similar_emails(user_request)
        email_result = self.generate_email_from_context(user_request, context_emails)
        return self.remove_similar_sentences(email_result)